// Bundles coach-framework/ into:
//   api/_lib/framework.js     prompts, rubric, schema, catalog (server only)
//   problem-coach/catalog.js  skills catalog + rubric IDs (public, for the UI)
// Run after editing anything in coach-framework/:  node scripts/build-coach-framework.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fw = (p) => fs.readFileSync(path.join(root, "coach-framework", p), "utf8");

// Split a markdown file on "## STAGE n" / "## Stage n" headings.
function splitStages(md) {
  const out = {};
  const re = /^## (?:STAGE|Stage) (\d)\b.*$/gm;
  const marks = [...md.matchAll(re)];
  marks.forEach((m, i) => {
    const end = i + 1 < marks.length ? marks[i + 1].index : md.length;
    out[m[1]] = md.slice(m.index, end).replace(/\n---\s*$/m, "").trim();
  });
  return out;
}

const stageGuides = splitStages(fw("prompts/stage-guides.md"));
const rubricMd = fw("spec/02-rubric.md");
const rubric = splitStages(rubricMd.split(/^## Calibration notes/m)[0]);
const calibration = "## Calibration notes" + rubricMd.split(/^## Calibration notes/m)[1];

// Criterion rows: | `P1_specific` | text | ✔ |
const criteria = {};
for (const [stage, block] of Object.entries(rubric)) {
  criteria[stage] = [...block.matchAll(/^\| `([A-Z]\d_[a-z_]+)` \| (.+?) \|\s*(.*?)\s*\|$/gm)].map((m) => ({
    id: m[1],
    label: m[2].trim(),
    required: m[3].includes("✔"),
    conditional: /only if/i.test(m[3]),
  }));
}

// Structured outputs reject length/number/array-size constraints and patterns;
// strip them for the API and enforce limits in the route instead.
function stripForApi(node) {
  if (Array.isArray(node)) return node.map(stripForApi);
  if (!node || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (["maxLength", "minLength", "minimum", "maximum", "maxItems", "minItems", "pattern", "description", "$schema", "title"].includes(k)) continue;
    out[k] = stripForApi(v);
  }
  return out;
}
const coachSchema = JSON.parse(fw("schema/coach-response.schema.json"));
// Every property must be listed in `required` for structured outputs to keep the shape stable.
coachSchema.required = Object.keys(coachSchema.properties);

const catalog = JSON.parse(fw("schema/skills-catalog.json"));
const briefWriter = fw("prompts/brief-writer.md").replace(
  /\(The API route appends templates\/requirements-doc\.md here\.\)\s*$/,
  fw("templates/requirements-doc.md")
);

const server = {
  COACH_SYSTEM: fw("prompts/coach-system.md").trim(),
  STAGE_GUIDES: stageGuides,
  RUBRIC: rubric,
  CALIBRATION: calibration.trim(),
  CRITERIA: criteria,
  COACH_SCHEMA: stripForApi(coachSchema),
  COACH_SCHEMA_FULL: JSON.parse(fw("schema/coach-response.schema.json")),
  BRIEF_WRITER: briefWriter.trim(),
  CATALOG: catalog,
};

const banner = "// GENERATED by scripts/build-coach-framework.mjs from coach-framework/. Do not edit by hand.\n";
fs.writeFileSync(
  path.join(root, "api/_lib/framework.js"),
  banner + "module.exports = " + JSON.stringify(server, null, 2) + ";\n"
);
fs.writeFileSync(
  path.join(root, "problem-coach/catalog.js"),
  banner + "window.COACH_FRAMEWORK = " + JSON.stringify({ catalog, criteria }, null, 2) + ";\n"
);

const counts = Object.entries(criteria).map(([s, c]) => `${s}:${c.length}`).join(" ");
console.log(`framework built — stages ${Object.keys(stageGuides).join(",")}; criteria ${counts}; skills ${catalog.skills.length}`);
